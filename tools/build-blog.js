#!/usr/bin/env node
/*
 * Build the static blog:
 *   blog/_posts/*.md  ->  blog/index.html + blog/<slug>/index.html
 *
 * Usage:
 *   node tools/build-blog.js            # skip draft: true
 *   node tools/build-blog.js --drafts   # include drafts (local preview)
 *
 * The generated HTML is committed; the site itself stays build-free.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');
const MarkdownIt = require('markdown-it');
const anchor = require('markdown-it-anchor');
const katexPlugin = require('@vscode/markdown-it-katex').default;

const ROOT = path.resolve(__dirname, '..');
const POSTS_DIR = path.join(ROOT, 'blog', '_posts');
const OUT_DIR = path.join(ROOT, 'blog');
const INCLUDE_DRAFTS = process.argv.includes('--drafts');
const MARKER = '<!-- generated by tools/build-blog.js; edit blog/_posts instead -->';
const SITE = 'https://bluecontra.github.io';
const SITE_DESC = 'Hongyao Tang (汤宏垚) — Associate Research Fellow at Tianjin University. Research on Deep Reinforcement Learning, Continual RL, and Embodied Intelligence.';

/* ------------------------------------------------------------------ */
/* helpers                                                             */
/* ------------------------------------------------------------------ */

function escapeHtml(value) {
  return String(value == null ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function stripTags(html) {
  return String(html || '')
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

function plainText(html) {
  return stripTags(html);
}

function formatDate(value) {
  const d = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(d.getTime())) return String(value || '');
  const y = d.getUTCFullYear();
  const m = String(d.getUTCMonth() + 1).padStart(2, '0');
  const day = String(d.getUTCDate()).padStart(2, '0');
  return `${y}.${m}.${day}`;
}

function dateValue(value) {
  const d = value instanceof Date ? value : new Date(value);
  return Number.isNaN(d.getTime()) ? 0 : d.getTime();
}

function slugify(text) {
  return String(text || '')
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '') || 'section';
}

function postSlug(data, filename) {
  const raw = data.slug || path.basename(filename, '.md');
  return String(raw)
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}-]+/gu, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '') || 'post';
}

function readingMinutes(source) {
  const cjk = (source.match(/[㐀-鿿豈-﫿]/g) || []).length;
  const rest = source.replace(/[㐀-鿿豈-﫿]/g, ' ');
  const words = (rest.match(/[A-Za-z0-9]+/g) || []).length;
  return Math.max(1, Math.ceil(cjk / 400 + words / 200));
}

function tagList(tags) {
  if (!tags) return [];
  if (Array.isArray(tags)) return tags.map(String).filter(Boolean);
  return String(tags).split(',').map(function (t) { return t.trim(); }).filter(Boolean);
}

function summaryOf(data, html) {
  if (data.summary) return String(data.summary).trim();
  const text = plainText(html);
  return text.length > 180 ? text.slice(0, 177).replace(/\s+\S*$/, '') + '…' : text;
}

// Copy images/resources referenced as relative "assets/..." paths from
// blog/_posts/assets into the generated post directory, so the markdown can
// keep using plain relative paths.
function copyPostAssets(html, outDir) {
  const assetsRoot = path.join(POSTS_DIR, 'assets');

  const outAssets = path.join(outDir, 'assets');
  if (fs.existsSync(outAssets)) {
    fs.rmSync(outAssets, { recursive: true, force: true });
  }
  if (!fs.existsSync(assetsRoot)) return;

  const re = /(?:src|href)="((?:\.\/)?assets\/[^"]+)"/gi;
  const seen = new Set();
  let m;
  while ((m = re.exec(html))) {
    const rel = m[1].replace(/^\.\//, '');
    if (seen.has(rel)) continue;
    seen.add(rel);

    const src = path.resolve(POSTS_DIR, rel);
    if (src !== assetsRoot && !src.startsWith(assetsRoot + path.sep)) continue;
    if (!fs.existsSync(src)) {
      console.warn('missing asset: ' + rel);
      continue;
    }

    const dest = path.join(outDir, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(src, dest);
  }
}

