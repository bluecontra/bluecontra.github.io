const md = new MarkdownIt({
  html: true,
  linkify: true,
  typographer: false,
  breaks: false
});

md.use(anchor, {
  slugify: slugify,
  permalink: false,
  level: [2, 3]
});

md.use(katexPlugin, {
  throwOnError: false,
  errorColor: '#cc0000'
});

// Wrap tables so they can scroll horizontally on narrow screens.
const defaultTableOpen = md.renderer.rules.table_open || function (tokens, idx, options, env, self) {
  return self.renderToken(tokens, idx, options);
};
const defaultTableClose = md.renderer.rules.table_close || function (tokens, idx, options, env, self) {
  return self.renderToken(tokens, idx, options);
};
md.renderer.rules.table_open = function (tokens, idx, options, env, self) {
  return '<div class="table-wrap">' + defaultTableOpen(tokens, idx, options, env, self);
};
md.renderer.rules.table_close = function (tokens, idx, options, env, self) {
  return defaultTableClose(tokens, idx, options, env, self) + '</div>';
};

// External links open in a new tab, like the rest of the site.
const defaultLinkOpen = md.renderer.rules.link_open || function (tokens, idx, options, env, self) {
  return self.renderToken(tokens, idx, options);
};
md.renderer.rules.link_open = function (tokens, idx, options, env, self) {
  const href = tokens[idx].attrGet('href') || '';
  if (/^https?:\/\//i.test(href)) {
    tokens[idx].attrSet('target', '_blank');
    tokens[idx].attrSet('rel', 'noopener');
  }
  return defaultLinkOpen(tokens, idx, options, env, self);
};

