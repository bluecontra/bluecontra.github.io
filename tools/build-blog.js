function card(group, lang) {
  const p = group.byLang[lang] || group.defaultPost;
  const linkLang = group.byLang[lang] ? lang : group.defaultLang;
  const tags = p.tags.map(function (t) {
    return `<span class="blog-tag">${escapeHtml(t)}</span>`;
  }).join('');
  const draft = p.draft ? '<span class="blog-draft">Draft</span>' : '';
  return `        <a class="blog-card" href="${pagePath(group, linkLang)}">
          <div class="blog-card-meta">
            <span class="blog-card-date">${escapeHtml(p.dateLabel)}</span>
            <span class="blog-card-dot">·</span>
            <span class="blog-card-time">${p.minutes} min read</span>
            ${draft}
          </div>
          <h2 class="blog-card-title">${escapeHtml(p.title)}</h2>
          <p class="blog-card-summary">${escapeHtml(p.summary)}</p>
          <div class="blog-card-bottom">
            <span class="blog-card-tags">${tags}</span>
          </div>
        </a>`;
}

function indexLangSwitch(current) {
  const zh = current === 'zh'
    ? '<span class="active">中文</span>'
    : '<a href="/blog/">中文</a>';
  const en = current === 'en'
    ? '<span class="active">English</span>'
    : '<a href="/blog/en/">English</a>';
  return `<span class="blog-lang-switch">${zh}<span class="sep">|</span>${en}</span>`;
}

function renderIndex(lang) {
  const isZh = lang === 'zh';
  const countLabel = groups.length + (groups.length === 1 ? ' post' : ' posts');
  const cards = groups.length
    ? groups.map(function (g) { return card(g, lang); }).join('\n')
    : '        <p class="blog-empty">No posts yet.</p>';

  return head({
    title: "Welcome to Hongyao's Log · Hongyao Tang",
    description: 'Notes by Hongyao Tang on reinforcement learning, large models, and embodied intelligence.',
    url: SITE + (isZh ? '/blog/' : '/blog/en/'),
    langAttr: isZh ? 'zh-CN' : 'en',
    blogHref: isZh ? '/blog/' : '/blog/en/',
    alternates: [
      { hreflang: 'zh-CN', url: SITE + '/blog/' },
      { hreflang: 'en', url: SITE + '/blog/en/' }
    ]
  }) + `
    <div class="trans">
      <header class="blog-index-header">
        <h1>Welcome to Hongyao's Log</h1>
        <div class="blog-index-subline">
          <p>Here, I produce logs (actually, my mind trash) sporadically. <span class="blog-count">${countLabel}</span></p>
          ${indexLangSwitch(lang)}
        </div>
      </header>

      <div class="blog-list">
${cards}
      </div>
    </div>
` + foot();
}

fs.writeFileSync(path.join(OUT_DIR, 'index.html'), renderIndex('zh'));
fs.mkdirSync(path.join(OUT_DIR, 'en'), { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, 'en', 'index.html'), renderIndex('en'));

/* ------------------------------------------------------------------ */
/* write post pages                                                    */
/* ------------------------------------------------------------------ */

groups.forEach(function (group, gi) {
  const newerGroup = groups[gi - 1];
  const olderGroup = groups[gi + 1];

  // Rebuild the whole post directory so removed translations or assets do not linger.
  const groupDir = path.join(OUT_DIR, group.key);
  if (fs.existsSync(groupDir)) {
    fs.rmSync(groupDir, { recursive: true, force: true });
  }
  fs.mkdirSync(groupDir, { recursive: true });

  group.order.forEach(function (lang) {
    const p = group.byLang[lang];
    const isDefault = lang === group.defaultLang;
    const outDir = isDefault ? groupDir : path.join(groupDir, lang);
    fs.mkdirSync(outDir, { recursive: true });

    const newer = newerGroup ? (newerGroup.byLang[lang] || newerGroup.defaultPost) : null;
    const older = olderGroup ? (olderGroup.byLang[lang] || olderGroup.defaultPost) : null;

    const tags = p.tags.map(function (t) {
      return `<span class="blog-tag">${escapeHtml(t)}</span>`;
    }).join('');
    const draft = p.draft ? '<span class="blog-draft">Draft</span>' : '';

    let prevNext = '';
    if (newer || older) {
      prevNext = `      <nav class="blog-post-nav" aria-label="More posts">
${newer ? `        <a class="blog-post-prev" href="${pagePath(newerGroup, newer.lang)}"><span>Newer</span>${escapeHtml(newer.title)}</a>` : '        <span></span>'}
${older ? `        <a class="blog-post-next" href="${pagePath(olderGroup, older.lang)}"><span>Older</span>${escapeHtml(older.title)}</a>` : '        <span></span>'}
      </nav>`;
    }

    const page = head({
      title: p.title + ' · Hongyao Tang',
      description: p.summary,
      url: pageUrl(group, lang),
      type: 'article',
      katex: true,
      bodyClass: 'blog-post-page',
      langAttr: lang === 'zh' ? 'zh-CN' : lang,
      blogHref: lang === 'en' ? '/blog/en/' : '/blog/',
      alternates: group.order.map(function (l) {
        return { hreflang: l === 'zh' ? 'zh-CN' : l, url: pageUrl(group, l) };
      })
    }) + tocNav(p.headings) + `
    <a class="blog-back" href="/blog/">← Back to All Logs</a>

    <div class="trans">
      <header class="blog-post-header">
        <div class="blog-post-meta">
          <span>${escapeHtml(p.dateLabel)}</span>
          <span class="blog-card-dot">·</span>
          <span>${p.minutes} min read</span>
          ${draft}
          ${langSwitch(group, lang)}
        </div>
        <h1>${escapeHtml(p.title)}</h1>
        ${p.summary ? `<p class="blog-post-summary">${escapeHtml(p.summary)}</p>` : ''}
        ${tags ? `<div class="blog-post-tags">${tags}</div>` : ''}
      </header>

${tocDetails(p.headings)}      <article class="blog-article">
${p.html}
      </article>

${prevNext}

    </div>
` + scrollSpy + foot();

    fs.writeFileSync(path.join(outDir, 'index.html'), page);
    copyPostAssets(p.html, outDir);
  });
});

/* ------------------------------------------------------------------ */
/* clean generated post dirs that are no longer published              */
/* ------------------------------------------------------------------ */

fs.readdirSync(OUT_DIR, { withFileTypes: true }).forEach(function (entry) {
  // "en" is the generated English blog index, not a post directory.
  if (!entry.isDirectory() || entry.name === '_posts' || entry.name === 'en') return;
  const indexPath = path.join(OUT_DIR, entry.name, 'index.html');
  if (!fs.existsSync(indexPath)) return;
  const content = fs.readFileSync(indexPath, 'utf8');
  if (!content.includes(MARKER)) return;
  if (groupKeys.has(entry.name)) return;
  fs.rmSync(path.join(OUT_DIR, entry.name), { recursive: true, force: true });
  console.log('removed stale post: blog/' + entry.name + '/');
});

